def render_help(message: str = "/help") -> str:
    parts = message.strip().split(maxsplit=1)
    if len(parts) == 1 or not parts[1].strip():
        return HELP_OVERVIEW
    requested = parts[1].strip().casefold().replace("ё", "е")
    topic = TOPIC_ALIASES.get(requested)
    if topic is None:
        return "Не нашёл такой раздел. Используйте /help и выберите раздел из списка."
    return HELP_TOPICS[topic]


def telegram_menu_commands() -> list[dict[str, str]]:
    return [{"command": command, "description": description}
            for command, description in MENU_COMMANDS]
